// PREDICTIONS SCHEMA SETUP
CREATE SCHEMA IF NOT EXISTS PREDICTIONS;
USE SCHEMA PREDICTIONS;

//TABLE DEFINITIONS

TB Adherence Predictions

CREATE OR REPLACE TABLE PREDICTIONS.TB_ADHERENCE_PREDICTIONS (
    PREDICTION_ID VARCHAR(50) DEFAULT UUID_STRING(),
    STUDYNUMBER INT, 
    PREDICTION_DATE TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PREDICTED_PROBABILITY FLOAT, -- Probability of Poor Outcome / Loss to Follow-up
    RISK_LEVEL VARCHAR(20),     -- 'High', 'Medium', 'Low'
    MODEL_VERSION VARCHAR(50),  -- e.g., 'v1.0.0'
    METADATA VARIANT            -- Extra info (e.g., top contributing features)
);

-- HIV Adherence Predictions
-- Key: INCLUDED_CASES (from HIV_ADHERENCE_DATASET)
CREATE OR REPLACE TABLE PREDICTIONS.HIV_ADHERENCE_PREDICTIONS (
    PREDICTION_ID VARCHAR(50) DEFAULT UUID_STRING(),
    CASE_ID VARCHAR(50),        -- Maps to INCLUDED_CASES
    PREDICTION_DATE TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PREDICTED_VIRAL_SUPPRESSION FLOAT, -- Probability of Viral Suppression
    PREDICTED_DEPRESSION_RISK FLOAT,   -- Probability of Depression (PHQ-9)
    MODEL_VERSION VARCHAR(50),
    METADATA VARIANT
);

-- Quality of Care / Facility Predictions (Future Placeholder)
CREATE OR REPLACE TABLE PREDICTIONS.FACILITY_RISK_PREDICTIONS (
    PREDICTION_ID VARCHAR(50) DEFAULT UUID_STRING(),
    FACILITY_TYPE VARCHAR(50),
    PREDICTION_DATE TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    RISK_SCORE FLOAT,
    MODEL_VERSION VARCHAR(50)
);
