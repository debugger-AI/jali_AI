-- 1. DATABASE & WAREHOUSE SETUP
CREATE DATABASE IF NOT EXISTS JALI_ML_DB;
USE DATABASE JALI_ML_DB;

CREATE WAREHOUSE IF NOT EXISTS JALI_ML_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 120
    AUTO_RESUME = TRUE;

USE WAREHOUSE JALI_ML_WH;

-- 2. SCHEMAS
CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS ANALYTICS;
CREATE SCHEMA IF NOT EXISTS FEATURES;

-- 3. FILE FORMATS & STAGES (IN RAW SCHEMA)
USE SCHEMA RAW;

CREATE OR REPLACE FILE FORMAT RAW.CSV_FORMAT
    TYPE = 'CSV'
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    SKIP_HEADER = 1
    NULL_IF = ('', 'NA', 'N/A', 'null', 'NULL', 'None', 'NaN')
    TRIM_SPACE = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

CREATE OR REPLACE STAGE RAW.JALI_CSV_STAGE
    FILE_FORMAT = RAW.CSV_FORMAT;

-- 4. TABLE DEFINITIONS

CREATE OR REPLACE TABLE RAW.CRT_DATASET (
    STUDYNUMBER INT, INANALYSIS INT, PROVINCE INT, COUNTYID INT,
    ARM INT, STRATA INT, GENDER INT, AGECAT_CALC INT,
    OCCUPATION_CALC INT, EDUCATIONLEVEL INT, MARRIED_CALC INT,
    RESIDENCE INT, INCOMCAT_CALC INT, DISTTBCL_CALC FLOAT,
    DISTSUPERV_CALC FLOAT, MEDINSUR_CALC INT, SMEARTEST INT,
    OUTCOME_LOSTFUP INT, OUTCOME_POOR INT,
    MISS3DOSE INT, MISS7DOSE INT, PILLCOUNT FLOAT,
    TOTALMISSED_CM FLOAT, TOTALMISSED_PC FLOAT, TOTALMISSED_CM10 FLOAT,
    MONITORPROBLEM INT,
    IM_DOCTOR FLOAT, IM_MEDMON FLOAT, IM_SWITCHED FLOAT,
    DOT_DOCTOR FLOAT, DOT_MEDMON FLOAT, DOT_SWITCHED FLOAT
);

CREATE OR REPLACE TABLE RAW.FEDCYCLEDATA (
    CLIENTID VARCHAR(50), CYCLENUMBER INT, GROUPID INT,
    CYCLEWITHPEAKORNOT INT, REPRODUCTIVECATEGORY INT,
    LENGTHOFCYCLE FLOAT, MEANCYCLELENGTH FLOAT,
    ESTIMATEDDAYOFOVULATION FLOAT, LENGTHOFLUTEALPHASE FLOAT,
    AGE FLOAT, BMI FLOAT
);

CREATE OR REPLACE TABLE RAW.QUALITYOFCARE (
    HEALTH_FACILITY_LEVEL VARCHAR(100), FACILITYTYPE VARCHAR(50),
    AGE FLOAT, SEX VARCHAR(10),
    CD4ATSTART FLOAT, VIRALLOAD VARCHAR(50)
);

CREATE OR REPLACE TABLE RAW.HIV_ADHERENCE_DATASET (
    INCLUDED_CASES VARCHAR(20), UKVSUSA VARCHAR(10),
    AGE_YEARS FLOAT, GENDER VARCHAR(50),
    MARSTOTAL FLOAT, PHQ_TOTAL_AF FLOAT
);

CREATE OR REPLACE TABLE RAW.IMMUNIZATION_SCHEDULE (
    AGE VARCHAR(50),
    VACCINE_NAME VARCHAR(100),
    DOSE VARCHAR(100),
    PREVENTS VARCHAR(500),
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

