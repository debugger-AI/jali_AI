UNION ALL SELECT 'FEDCYCLEDATA', COUNT(*) FROM RAW.FEDCYCLEDATA
UNION ALL SELECT 'QUALITYOFCARE', COUNT(*) FROM RAW.QUALITYOFCARE
UNION ALL SELECT 'HIV_ADHERENCE', COUNT(*) FROM RAW.HIV_ADHERENCE_DATASET
UNION ALL SELECT 'IMMUNIZATION', COUNT(*) FROM RAW.IMMUNIZATION_SCHEDULE;

-- 8. ML ANALYTICS VIEW - IMMUNIZATION
USE SCHEMA ANALYTICS;

CREATE OR REPLACE VIEW ANALYTICS.ML_IMMUNIZATION_SCHEDULE AS
SELECT 
    VACCINE_NAME,
    AGE AS AGE_LABEL,
    CASE 
        WHEN AGE = 'Birth' THEN 0
        WHEN AGE = '6 Weeks' THEN 42
        WHEN AGE = '10 Weeks' THEN 70
        WHEN AGE = '14 Weeks' THEN 98
        WHEN AGE = '6 Months' THEN 182
        WHEN AGE = '7 Months' THEN 212
        WHEN AGE = '9 Months' THEN 273
        WHEN AGE = '12 Months' THEN 365
        WHEN AGE = '18 Months' THEN 547
        WHEN AGE = '2 Years' THEN 730
        ELSE NULL 
    END AS DUE_DAYS_FROM_BIRTH,
    DOSE,
    PREVENTS
FROM RAW.IMMUNIZATION_SCHEDULE;
